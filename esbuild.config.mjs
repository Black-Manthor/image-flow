import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { writeFileSync } from 'node:fs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';
// `copertura <file>`: one build mapped back to the sources, for
// tests/copertura.mjs (npm run test:copertura). Never the release.
const coverage = process.argv[2] === 'copertura' ? process.argv[3] : undefined;
// `mappa <file>`: the production build again, with its source map written
// beside it and not referenced in the file, so the code is the release's: the
// real-app tests map the plugin's errors back to the sources. Never the release.
const mapped = process.argv[2] === 'mappa' ? process.argv[3] : undefined;

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: mapped ? 'external' : prod ? false : 'inline',
	treeShaking: true,
	outfile: coverage ?? mapped ?? 'main.js',
	minify: prod || Boolean(mapped),
});

if (prod || coverage || mapped) {
	// For tests/registro-comando.mjs (`npm run build`): how many errors and
	// warnings esbuild reported, from its results, written to the file
	// IW_DIAGNOSTICHE names. Its summary of the files written goes to the same
	// stderr as its warnings, so its output cannot tell them apart. The build
	// and its output are the same with or without it.
	// With them, the first 100 messages (severity, id, message, file, line,
	// column), the others counted in `omitted`; a long message is cut, with its
	// length kept.
	const counts = result => {
		if (!process.env.IW_DIAGNOSTICHE) return;
		const messages = [...(result.errors ?? []).map(message => ['error', message]), ...(result.warnings ?? []).map(message => ['warning', message])];
		const items = messages.slice(0, 100).map(([severity, { id, pluginName, text, location }]) => ({
			severity, id: id || null, ...(pluginName ? { plugin: pluginName } : {}), message: String(text ?? '').slice(0, 500),
			...(String(text ?? '').length > 500 ? { messageLength: String(text).length } : {}),
			...(location ? { file: location.file, line: location.line, column: location.column } : {}),
		}));
		writeFileSync(process.env.IW_DIAGNOSTICHE, JSON.stringify({ tool: 'esbuild', errors: result.errors?.length ?? 0, warnings: result.warnings?.length ?? 0, items, omitted: messages.length - items.length }));
	};
	try {
		counts(await context.rebuild());
	} catch (error) {
		if (Array.isArray(error?.errors)) counts(error);
		throw error;
	}
	process.exit(0);
} else {
	await context.watch();
}
